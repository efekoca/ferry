// Writes crates/ferry-core/src/constants.rs: every global constant of the newest PHP dump, so an
// AI suggestion that uses a constant PHP doesn't define can be refused.
// Usage: node scripts/php-symbols/constants.mjs <folder with php-X.Y.json dumps from dump.sh>
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const folder = process.argv[2];
if (!folder) throw new Error("usage: node scripts/php-symbols/constants.mjs <dump-folder>");
const version = (file) => file.match(/(\d+)\.(\d+)/).slice(1).map(Number);
const newest = readdirSync(folder)
  .filter((f) => /^php-\d+\.\d+\.json$/.test(f))
  .sort((a, b) => version(a)[0] - version(b)[0] || version(a)[1] - version(b)[1])
  .at(-1);
const dump = JSON.parse(readFileSync(join(folder, newest), "utf8"));
const names = Object.keys(dump.constants).filter((k) => !k.includes("::") && !k.includes("\\")).sort();
const body = names.map((n) => `    ${JSON.stringify(n)},`).join("\n");
writeFileSync(
  "crates/ferry-core/src/constants.rs",
  `// Generated by scripts/php-symbols/constants.mjs from PHP ${dump.version}. Don't edit by hand.\n\n` +
    `/// Every global constant PHP ${dump.version} defines with the extensions of the dump image, sorted.\n` +
    `pub const CONSTANTS: &[&str] = &[\n${body}\n];\n`,
);
console.log(`${names.length} constants from PHP ${dump.version}`);
