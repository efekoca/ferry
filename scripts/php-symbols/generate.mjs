// Turns the reflection dumps of consecutive PHP versions into crates/ferry-core/src/symbols.rs:
// node scripts/php-symbols/generate.mjs <dump-folder> > crates/ferry-core/src/symbols.rs
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const folder = process.argv[2];
if (!folder) {
  console.error("usage: generate.mjs <dump-folder>");
  process.exit(2);
}

const line = (v) => v.split(".").slice(0, 2).map(Number);
const dumps = readdirSync(folder)
  .filter((f) => /^php-\d+\.\d+\.json$/.test(f))
  .map((f) => JSON.parse(readFileSync(join(folder, f), "utf8")))
  .sort((a, b) => line(a.version)[0] - line(b.version)[0] || line(a.version)[1] - line(b.version)[1]);

const removedFunctions = new Map();
const deprecatedFunctions = new Map();
const removedClasses = new Map();
const removedMethods = new Map();
const deprecatedMethods = new Map();
const removedConstants = new Map();
const deprecatedConstants = new Map();
const removedIni = new Map();
const typedConstants = new Map();
const first = (map, key, value) => map.has(key) || map.set(key, value);
const latest = dumps[dumps.length - 1];
// Functions that only exist when the build host supports them, so their absence isn't a removal.
const BUILD_DEPENDENT = new Set(["pcntl_setns"]);

// A method that left a class but stayed on one of its subclasses moved down the hierarchy
// (ReflectionType::isBuiltin went to ReflectionNamedType in 8.0). Dumps list inherited methods,
// so a subclass is a class that had every public method of the parent.
const movedDown = (prev, name, method) => {
  const parent = Object.keys(prev.classes[name].methods);
  return Object.entries(prev.classes).some(
    ([other, c]) => other !== name && parent.every((m) => c.methods[m]) && latest.classes[other]?.methods[method],
  );
};

for (let i = 1; i < dumps.length; i++) {
  const prev = dumps[i - 1];
  const next = dumps[i];
  const since = line(next.version);
  const kept = new Set(next.extensions);

  for (const [name, f] of Object.entries(prev.functions)) {
    if (!next.functions[name] && !latest.functions[name] && kept.has(f.ext) && !BUILD_DEPENDENT.has(name)) first(removedFunctions, name, [since, f.ext]);
  }
  for (const [name, f] of Object.entries(next.functions)) {
    if (f.deprecated && !prev.functions[name]?.deprecated && latest.functions[name]?.deprecated !== false) first(deprecatedFunctions, name, [since, f.ext]);
  }
  for (const [name, c] of Object.entries(prev.classes)) {
    const now = next.classes[name];
    if (!now) {
      if (kept.has(c.ext) && !latest.classes[name]) first(removedClasses, name, [since, c.ext, c.name]);
      continue;
    }
    for (const method of Object.keys(c.methods)) {
      if (!now.methods[method] && latest.classes[name] && !latest.classes[name].methods[method] && !movedDown(prev, name, method))
        first(removedMethods, `${name}::${method}`, [since, c.name]);
    }
  }
  for (const [name, c] of Object.entries(next.classes)) {
    const before = prev.classes[name];
    if (!before) continue;
    for (const [method, m] of Object.entries(c.methods)) {
      if (m.deprecated && before.methods[method] && !before.methods[method].deprecated && latest.classes[name]?.methods[method]?.deprecated !== false)
        first(deprecatedMethods, `${name}::${method}`, [since, c.name]);
    }
  }
  for (const [name, c] of Object.entries(prev.constants)) {
    if (!next.constants[name] && !latest.constants[name] && kept.has(c.ext)) first(removedConstants, name, [since, c.ext]);
  }
  for (const [name, c] of Object.entries(next.constants)) {
    if (c.deprecated && !prev.constants[name]?.deprecated && latest.constants[name]?.deprecated !== false) first(deprecatedConstants, name, [since, c.ext]);
  }
  for (const [name, c] of Object.entries(next.classes)) {
    const now = latest.classes[name];
    if (c.final || !now || now.final) continue;
    for (const k of Object.keys(c.typed ?? {})) {
      if (!prev.classes[name]?.typed?.[k] && now.typed?.[k]) first(typedConstants, `${name}::${k}`, [since, now.typed[k]]);
    }
  }
  for (const [name, ext] of Object.entries(prev.ini)) {
    if (!(name in next.ini) && !(name in latest.ini) && kept.has(ext)) first(removedIni, name, [since, ext]);
  }
}

const versions = dumps.map((d) => d.version).join(", ");
const str = (s) => JSON.stringify(s);
const ver = ([a, b]) => `(${a}, ${b})`;
const sorted = (map) => [...map.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const table = (name, doc, map, row) =>
  `/// ${doc}\npub const ${name}: &[${row.type}] = &[\n${sorted(map)
    .map(([k, v]) => `    ${row.fmt(k, v)},`)
    .join("\n")}\n];\n`;

const out = [
  `// Generated by scripts/php-symbols/generate.mjs from PHP ${versions}. Don't edit by hand.\n`,
  table("REMOVED_FUNCTIONS", "(function, removed in, extension); the extension itself stayed", removedFunctions, {
    type: "(&str, (u32, u32), &str)",
    fmt: (k, [s, e]) => `(${str(k)}, ${ver(s)}, ${str(e)})`,
  }),
  table("DEPRECATED_FUNCTIONS", "(function, deprecated in, extension)", deprecatedFunctions, {
    type: "(&str, (u32, u32), &str)",
    fmt: (k, [s, e]) => `(${str(k)}, ${ver(s)}, ${str(e)})`,
  }),
  table("REMOVED_CLASSES", "(class lowercase, removed in, extension, class name)", removedClasses, {
    type: "(&str, (u32, u32), &str, &str)",
    fmt: (k, [s, e, n]) => `(${str(k)}, ${ver(s)}, ${str(e)}, ${str(n)})`,
  }),
  table("REMOVED_METHODS", "(class::method lowercase, removed in, class name)", removedMethods, {
    type: "(&str, (u32, u32), &str)",
    fmt: (k, [s, n]) => `(${str(k)}, ${ver(s)}, ${str(n)})`,
  }),
  table("DEPRECATED_METHODS", "(class::method lowercase, deprecated in, class name)", deprecatedMethods, {
    type: "(&str, (u32, u32), &str)",
    fmt: (k, [s, n]) => `(${str(k)}, ${ver(s)}, ${str(n)})`,
  }),
  table("REMOVED_CONSTANTS", "(constant, removed in, extension)", removedConstants, {
    type: "(&str, (u32, u32), &str)",
    fmt: (k, [s, e]) => `(${str(k)}, ${ver(s)}, ${str(e)})`,
  }),
  table("DEPRECATED_CONSTANTS", "(constant, deprecated in, extension)", deprecatedConstants, {
    type: "(&str, (u32, u32), &str)",
    fmt: (k, [s, e]) => `(${str(k)}, ${ver(s)}, ${str(e)})`,
  }),
  table("TYPED_CONSTANTS", "(class lowercase::CONSTANT, typed in, type) for classes that can be extended", typedConstants, {
    type: "(&str, (u32, u32), &str)",
    fmt: (k, [s, t]) => `(${str(k)}, ${ver(s)}, ${str(t)})`,
  }),
  table("REMOVED_INI", "(ini setting, removed in, extension)", removedIni, {
    type: "(&str, (u32, u32), &str)",
    fmt: (k, [s, e]) => `(${str(k)}, ${ver(s)}, ${str(e)})`,
  }),
];
process.stdout.write(out.join("\n"));
