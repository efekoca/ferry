// Regenerates crates/ferry-core/src/builtin.rs from the images scripts/php-symbols/dump.sh builds:
// node scripts/builtin-methods.mjs > crates/ferry-core/src/builtin.rs
import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const VERSIONS = ["8.1", "8.2", "8.3", "8.4", "8.5"];
const dumps = VERSIONS.map((v) =>
  JSON.parse(
    execFileSync("docker", ["run", "--rm", "-v", `${resolve(here)}:/s:ro`, `ferry-php-symbols:${v}`, "php", "-d", "error_reporting=0", "/s/builtin-methods.php"], {
      encoding: "utf8",
      maxBuffer: 1 << 28,
    }),
  ),
);

const code = (v) => {
  const [a, b] = v.split(".").map(Number);
  return a * 100 + b;
};
const classes = new Map();
for (const dump of dumps) {
  for (const [name, row] of Object.entries(dump.classes)) {
    const entry = classes.get(name) ?? { parents: new Set(), methods: new Map() };
    classes.set(name, entry);
    row.parents.forEach((p) => entry.parents.add(p));
    for (const [method, shape] of Object.entries(row.methods)) {
      const ranges = entry.methods.get(method) ?? [];
      entry.methods.set(method, ranges);
      const key = JSON.stringify(shape);
      const last = ranges[ranges.length - 1];
      const version = code(dump.version);
      if (last && last.key === key && last.until + 1 === version) last.until = version;
      else ranges.push({ key, shape, from: version, until: version });
    }
  }
}

const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const str = (s) => JSON.stringify(s);
const first = code(VERSIONS[0]);
const last = code(VERSIONS[VERSIONS.length - 1]);
const out = [
  `// Generated by scripts/builtin-methods.mjs from PHP ${VERSIONS.join(", ")}. Do not edit by hand.`,
  "",
  "/// (by_ref, type)",
  "pub(crate) type Param = (bool, &'static str);",
  "/// (name, static, required, params, variadic, return type, tentative return type, first PHP, last PHP)",
  "/// PHP is written as 804; 0 means the row has no limit on that side.",
  "pub(crate) type Method = (&'static str, bool, usize, &'static [Param], bool, &'static str, bool, u32, u32);",
  "",
  "pub(crate) const CLASSES: &[(&str, &[&str], &[Method])] = &[",
];
for (const [name, { parents, methods }] of [...classes].sort(([a], [b]) => compare(a, b))) {
  out.push(`    (${str(name)}, &[${[...parents].sort(compare).map(str).join(", ")}], &[`);
  for (const [method, ranges] of [...methods].sort(([a], [b]) => compare(a, b))) {
    for (const { shape, from, until } of ranges) {
      const [isStatic, required, params, variadic, returns, tentative] = shape;
      const ps = params.map(([r, t]) => `(${r}, ${str(t)})`).join(", ");
      out.push(`        (${str(method)}, ${isStatic}, ${required}, &[${ps}], ${variadic}, ${str(returns)}, ${tentative}, ${from === first ? 0 : from}, ${until === last ? 0 : until}),`);
    }
  }
  out.push("    ]),");
}
out.push("];", "");
process.stdout.write(out.join("\n"));
