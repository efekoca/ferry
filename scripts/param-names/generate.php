<?php
// Writes crates/ferry-core/src/param_names.rs for the functions passed on stdin, one per line.
// Usage: php scripts/param-names/generate.php < functions.txt > crates/ferry-core/src/param_names.rs
$rows = [];
foreach (array_filter(array_map('trim', file('php://stdin'))) as $name) {
    if (!function_exists($name)) {
        continue;
    }
    $params = array_map(fn ($p) => '"' . $p->getName() . '"', (new ReflectionFunction($name))->getParameters());
    $rows[] = sprintf('    ("%s", &[%s]),', $name, implode(', ', $params));
}
echo "// Generated by scripts/param-names/generate.php.\n\n";
printf("pub(crate) const PARAM_NAMES: [(&str, &[&str]); %d] = [\n%s\n];\n", count($rows), implode("\n", $rows));
